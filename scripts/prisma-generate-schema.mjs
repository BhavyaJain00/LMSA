/**
 * Everything the generator would write, without writing it.
 * @param {string} [root]
 */
export async function generate(root = PROJECT_ROOT) {
  const ts = await loadTypeScript();
  const collections = readCollections(ts, path.join(root, "src/lib/db/store.ts"));
  const hotKeys = readHotKeys(ts, path.join(root, "src/lib/types.ts"), collections);
  const specs = buildTableSpecs(collections, hotKeys);
  return {
    specs,
    files: {
      [path.join(root, "prisma/schema.prisma")]: buildPrismaSchema(specs),
      [path.join(root, "src/lib/db/postgres-tables.mjs")]: buildTablesModule(specs),
    },
  };
}

/** Run the Prisma CLI of this project. */
function prisma(/** @type {string[]} */ args, /** @type {string} */ root) {
  const cli = path.join(root, "node_modules/prisma/build/index.js");
  return execFileSync(process.execPath, [cli, ...args], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], env: { ...process.env, PRISMA_HIDE_UPDATE_MESSAGE: "1" } });
}

/** `20261007123000` (UTC), the prefix Prisma gives migration folders. */
function migrationStamp(date = new Date()) {
  return date.toISOString().replace(/[-:T]/g, "").slice(0, 14);
}

/**
 * SQL turning the schema `from` (null = empty database) into `to`, from
 * `prisma migrate diff` (no database needed). Empty when nothing changes.
 */
export function migrationSql(/** @type {string | null} */ from, /** @type {string} */ to, root = PROJECT_ROOT) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "ll-prisma-"));
  try {
    const toFile = path.join(dir, "to.prisma");
    fs.writeFileSync(toFile, to);
    const fromArgs = from === null ? ["--from-empty"] : ["--from-schema-datamodel", path.join(dir, "from.prisma")];
    if (from !== null) fs.writeFileSync(path.join(dir, "from.prisma"), from);
    const sql = prisma(["migrate", "diff", ...fromArgs, "--to-schema-datamodel", toFile, "--script"], root);
    return /^\s*(--[^\n]*\n?\s*)*$/.test(sql) && !/;/.test(sql) ? "" : sql;
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

async function main() {
  const argv = process.argv.slice(2);
  const check = argv.includes("--check");
  const nameIndex = argv.indexOf("--name");
  const name = (nameIndex !== -1 ? argv[nameIndex + 1] : "") || "update_schema";
  if (!/^[a-z0-9_]{1,60}$/.test(name)) throw new Error("--name must be lowercase letters, digits and underscores.");

  const { specs, files } = await generate();
  const schemaFile = path.join(PROJECT_ROOT, "prisma/schema.prisma");
  const previous = fs.existsSync(schemaFile) ? fs.readFileSync(schemaFile, "utf8") : null;
  const stale = Object.entries(files).filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text);

  if (check) {
    if (stale.length) {
      console.error(`Out of date: ${stale.map(([file]) => path.relative(PROJECT_ROOT, file)).join(", ")}. Run "npm run prisma:schema".`);
      process.exitCode = 1;
    } else {
      console.log(`prisma/schema.prisma is up to date (${specs.length} collections).`);
    }
    return;
  }

  for (const [file, text] of stale) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    console.log(`wrote ${path.relative(PROJECT_ROOT, file)}`);
  }

  const migrationsDir = path.join(PROJECT_ROOT, "prisma/migrations");
  const hasMigrations = fs.existsSync(migrationsDir) && fs.readdirSync(migrationsDir).some((entry) => /^\d{14}_/.test(entry));
  const next = files[schemaFile];
  const sql = !hasMigrations ? migrationSql(null, next) : previous !== next && previous !== null ? migrationSql(previous, next) : "";
  if (sql) {
    const folder = path.join(migrationsDir, `${migrationStamp()}_${hasMigrations ? name : "init"}`);
    fs.mkdirSync(folder, { recursive: true });
    fs.writeFileSync(path.join(folder, "migration.sql"), sql);
    const lock = path.join(migrationsDir, "migration_lock.toml");
    if (!fs.existsSync(lock)) {
      fs.writeFileSync(lock, '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n');
    }
    console.log(`wrote ${path.relative(PROJECT_ROOT, folder)}/migration.sql`);
  } else if (!stale.length) {
    console.log(`Nothing to do: the schema is up to date (${specs.length} collections).`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : err);
    process.exitCode = 1;
  });
}
