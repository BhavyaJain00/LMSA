#!/usr/bin/env node
/**
 * Generate the PostgreSQL schema from the store's collections.
 *
 *   npm run prisma:schema                 regenerate; writes a migration when the schema changed
 *   npm run prisma:schema -- --name x     name the new migration (default "update_schema")
 *   npm run prisma:schema -- --check      exit 1 when the committed files are out of date
 *
 * Reads `COLLECTIONS` (src/lib/db/store.ts) and the document types
 * (src/lib/types.ts, through the TypeScript compiler) and writes:
 *
 *  - `prisma/schema.prisma`: one model per collection (`id`, `doc` jsonb,
 *    `position`, `updated_at`, plus a real, indexed column for each hot key
 *    the collection's type actually has), and the `settings` / `meta` tables;
 *  - `src/lib/db/postgres-tables.mjs`: the same table/column map for the
 *    store driver and the copy script;
 *  - a migration in `prisma/migrations/` (SQL from `prisma migrate diff`,
 *    which needs no database) when the schema changed.
 *
 * Adding a collection: add its type to `Database`, its name to
 * `COLLECTIONS`, run `npm run prisma:schema -- --name add_<collection>`,
 * commit the three outputs and run `npm run db:setup` on deploy.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";

export const PROJECT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** Document keys that get a real column (and index) wherever the collection's type has them. */
export const HOT_COLUMN_KEYS = Object.freeze(["userId", "courseId", "lessonId", "slug", "email"]);

const HEADER = "Generated by scripts/prisma-generate-schema.mjs from COLLECTIONS (src/lib/db/store.ts) and src/lib/types.ts. Do not edit: run `npm run prisma:schema`.";

/** `quizSubmissions` → `quiz_submissions`. */
export function snakeCase(/** @type {string} */ name) {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/([A-Z])([A-Z][a-z])/g, "$1_$2").toLowerCase();
}

/** `quizSubmissions` → `QuizSubmissions` (Prisma model name). */
export function modelName(/** @type {string} */ name) {
  return name.charAt(0).toUpperCase() + name.slice(1);
}

