/** Load the TypeScript compiler (a dev dependency). */
async function loadTypeScript() {
  const mod = await import("typescript");
  return /** @type {typeof import("typescript")} */ (mod.default ?? mod);
}

/**
 * The string literals of `export const COLLECTIONS = [...]` in store.ts.
 * @param {typeof import("typescript")} ts
 * @param {string} file
 * @returns {string[]}
 */
export function readCollections(ts, file) {
  const source = ts.createSourceFile(file, fs.readFileSync(file, "utf8"), ts.ScriptTarget.Latest, true);
  /** @type {string[] | null} */
  let names = null;
  source.forEachChild((node) => {
    if (!ts.isVariableStatement(node)) return;
    for (const decl of node.declarationList.declarations) {
      if (!ts.isIdentifier(decl.name) || decl.name.text !== "COLLECTIONS" || !decl.initializer) continue;
      let init = decl.initializer;
      while (ts.isAsExpression(init) || ts.isSatisfiesExpression(init) || ts.isParenthesizedExpression(init)) init = init.expression;
      if (!ts.isArrayLiteralExpression(init)) throw new Error("COLLECTIONS must be an array literal of strings.");
      names = init.elements.map((el) => {
        if (!ts.isStringLiteral(el)) throw new Error("COLLECTIONS must only contain string literals.");
        return el.text;
      });
    }
  });
  if (!names) throw new Error(`COLLECTIONS was not found in ${file}.`);
  return names;
}

/**
 * For each collection, the hot keys its document type has as a string
 * field (optional or not). Uses the type checker, so `extends`, aliases and
 * intersections are followed.
 *
 * @param {typeof import("typescript")} ts
 * @param {string} typesFile
 * @param {readonly string[]} collections
 * @returns {Record<string, string[]>}
 */
export function readHotKeys(ts, typesFile, collections) {
  const program = ts.createProgram([typesFile], { strict: true, noEmit: true, skipLibCheck: true, target: ts.ScriptTarget.ES2022 });
  const checker = program.getTypeChecker();
  const source = program.getSourceFile(typesFile);
  if (!source) throw new Error(`Could not read ${typesFile}.`);
  /** @type {import("typescript").InterfaceDeclaration | undefined} */
  let database;
  source.forEachChild((node) => {
    if (ts.isInterfaceDeclaration(node) && node.name.text === "Database") database = node;
  });
  if (!database) throw new Error(`interface Database was not found in ${typesFile}.`);
  const dbType = checker.getTypeAtLocation(database.name);

  /** @param {import("typescript").Type} type */
  const isStringLike = (type) => {
    const parts = type.isUnion() ? type.types : [type];
    let sawString = false;
    for (const part of parts) {
      const flags = part.getFlags();
      if (flags & (ts.TypeFlags.Undefined | ts.TypeFlags.Null)) continue;
      if (flags & ts.TypeFlags.StringLike) {
        sawString = true;
        continue;
      }
      return false;
    }
    return sawString;
  };

  /** @type {Record<string, string[]>} */
  const out = {};
  for (const name of collections) {
    const prop = checker.getPropertyOfType(dbType, name);
    if (!prop) throw new Error(`Collection "${name}" is in COLLECTIONS but not in interface Database.`);
    const arrayType = checker.getTypeOfSymbolAtLocation(prop, database);
    const element = checker.getIndexTypeOfType(arrayType, ts.IndexKind.Number);
    if (!element) throw new Error(`Database.${name} is not an array type.`);
    out[name] = HOT_COLUMN_KEYS.filter((key) => {
      const field = checker.getPropertyOfType(element, key);
      return Boolean(field && isStringLike(checker.getTypeOfSymbolAtLocation(field, database)));
    });
  }
  return out;
}

/* ------------------------------------------------------------------ */
/* Building the outputs                                                */
/* ------------------------------------------------------------------ */

/**
 * @typedef {object} TableSpec
 * @property {string} name     Collection name.
 * @property {string} model    Prisma model name.
 * @property {string} table    Table name.
 * @property {{ key: string; column: string }[]} columns  Extracted hot-key columns.
 */

/**
 * @param {readonly string[]} collections
 * @param {Record<string, readonly string[]>} hotKeys
 * @returns {TableSpec[]}
 */
export function buildTableSpecs(collections, hotKeys) {
  const seen = new Set(["settings", "meta"]);
  return collections.map((name) => {
    if (!/^[a-z][A-Za-z0-9]{0,50}$/.test(name)) throw new Error(`"${name}" cannot be used as a collection name.`);
    const table = snakeCase(name);
    if (seen.has(table)) throw new Error(`Collection "${name}" maps to the table "${table}", which is already used.`);
    seen.add(table);
    return {
      name,
      model: modelName(name),
      table,
      columns: (hotKeys[name] ?? []).map((key) => ({ key, column: snakeCase(key) })),
    };
  });
}

/** schema.prisma for `specs`. */
export function buildPrismaSchema(/** @type {TableSpec[]} */ specs) {
  const lines = [
    `// ${HEADER}`,
    "",
    "generator client {",
    '  provider = "prisma-client-js"',
    "}",
    "",
    "datasource db {",
    '  provider  = "postgresql"',
    "  // Supabase: the pooled connection (port 6543, ?pgbouncer=true&connection_limit=…) for the app.",
    '  url       = env("DATABASE_URL")',
    "  // Supabase: the direct (or session pooler) connection, used by `prisma migrate`.",
    '  directUrl = env("DIRECT_URL")',
    "}",
    "",
    "/// The site settings: a single row (id = 1).",
    "model Setting {",
    "  id        Int      @id @default(1)",
    "  data      Json",
    '  updatedAt DateTime @map("updated_at") @db.Timestamptz(3)',
    "",
    '  @@map("settings")',
    "}",
    "",
    "/// Storage bookkeeping: initialized_at, initialized_from, write_seq, ….",
    "model Meta {",
    "  key   String @id",
    "  value String",
    "",
    '  @@map("meta")',
    "}",
  ];
  for (const spec of specs) {
    const width = Math.max(9, ...spec.columns.map((c) => c.key.length));
    const field = (/** @type {string} */ name, /** @type {string} */ rest) => `  ${name.padEnd(width)} ${rest}`;
    lines.push("", `/// Collection "${spec.name}": one JSON document per row, in array order (position).`, `model ${spec.model} {`);
    lines.push(field("id", "String   @id"));
    lines.push(field("doc", "Json"));
    lines.push(field("position", "Int"));
    lines.push(field("updatedAt", 'DateTime @map("updated_at") @db.Timestamptz(3)'));
    for (const { key, column } of spec.columns) lines.push(field(key, key === column ? "String?" : `String?  @map("${column}")`));
    lines.push("");
    lines.push("  @@index([position, id])");
    for (const { key } of spec.columns) lines.push(`  @@index([${key}])`);
    lines.push(`  @@map("${spec.table}")`, "}");
  }
  return `${lines.join("\n")}\n`;
}

/** The generated table map module (`src/lib/db/postgres-tables.mjs`). */
export function buildTablesModule(/** @type {TableSpec[]} */ specs) {
  const rows = specs.map((spec) => {
    const columns = spec.columns.map((c) => `{ key: ${JSON.stringify(c.key)}, column: ${JSON.stringify(c.column)} }`).join(", ");
    return `  ${spec.name}: { table: ${JSON.stringify(spec.table)}, columns: [${columns}] },`;
  });
  return [
    `// ${HEADER}`,
    "",
    "/**",
    " * PostgreSQL table of each collection and the document keys copied into",
    " * real (indexed) columns. Used by the store driver (`postgres.ts`) and the",
    " * copy script (`scripts/db-copy-to-postgres.mjs`).",
    " *",
    " * @type {Readonly<Record<string, { table: string; columns: { key: string; column: string }[] }>>}",
    " */",
    "export const PG_TABLES = {",
    ...rows,
    "};",
    "",
  ].join("\n");
}

